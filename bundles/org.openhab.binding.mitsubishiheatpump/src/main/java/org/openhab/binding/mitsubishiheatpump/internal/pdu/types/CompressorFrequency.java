package org.openhab.binding.mitsubishiheatpump.internal.pdu.types;

import org.eclipse.jdt.annotation.NonNullByDefault;
import org.openhab.binding.mitsubishiheatpump.internal.exception.SerialProtocolException;
import org.openhab.core.library.types.QuantityType;
import org.openhab.core.library.unit.Units;
import org.openhab.core.types.State;

@NonNullByDefault
public class CompressorFrequency extends AbstractType implements MitsubishiHeatpumpType {
    public CompressorFrequency(byte value) throws SerialProtocolException {
        super(value);
    }

    @Override
    public State asState() {
        return new QuantityType<>(getValue(), Units.HERTZ);
    }
}
